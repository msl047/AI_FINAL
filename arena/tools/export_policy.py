def layers_from_state_dict(sd: dict, kind: str):
    sd = {k: v.detach().cpu().numpy() for k, v in sd.items()}
    if kind == "dqn":
        idx = sorted({int(m.group(1)) for k in sd for m in [re.match(r"net\.(\d+)\.weight", k)] if m})
        return [(sd[f"net.{i}.weight"], sd[f"net.{i}.bias"]) for i in idx], "relu"
    idx = sorted({int(m.group(1)) for k in sd for m in [re.match(r"trunk\.(\d+)\.weight", k)] if m})
    layers = [(sd[f"trunk.{i}.weight"], sd[f"trunk.{i}.bias"]) for i in idx]
    layers.append((sd["pi.weight"], sd["pi.bias"]))
    return layers, "tanh"


def export(state_dict_path: str, out_dir: str, kind: str):
    sd = torch.load(state_dict_path, map_location="cpu")
    if not isinstance(sd, dict) or not all(hasattr(v, "detach") for v in sd.values()):
        raise SystemExit("expected a state_dict saved with torch.save(net.state_dict(), path)")
    layers, act = layers_from_state_dict(sd, kind)
    if layers[0][0].shape[1] != 23:
        raise SystemExit(f"the first layer takes {layers[0][0].shape[1]} inputs; the arena observation has 23 (train on make_env('drill') or 'solo')")
    if layers[-1][0].shape[0] != 9:
        raise SystemExit(f"the output layer has {layers[-1][0].shape[0]} units; Tier 1 has 9 actions")
    os.makedirs(out_dir, exist_ok=True)
    arrays = {"n_layers": np.int64(len(layers)), "act": np.array(act)}
    for i, (W, b) in enumerate(layers):
        arrays[f"W{i}"], arrays[f"b{i}"] = W.astype(np.float32), b.astype(np.float32)
    np.savez(os.path.join(out_dir, "weights.npz"), **arrays)
    with open(os.path.join(out_dir, "agent.py"), "w") as f: f.write(AGENT_PY)
    with open(os.path.join(out_dir, "__init__.py"), "w") as f: f.write(INIT_PY)
    # self-check: the numpy forward pass reproduces the torch network on random inputs
    x = np.random.default_rng(0).normal(size=(8, 23)).astype(np.float32)
    h = x.T
    for i, (W, b) in enumerate(layers):
        h = W @ h + b[:, None]
        if i < len(layers) - 1: h = np.maximum(h, 0.0) if act == "relu" else np.tanh(h)
    print(f"wrote {out_dir}/ (weights.npz, agent.py, __init__.py): {len(layers)} layers, {act}; "
          f"sizes {[W.shape for W, _ in layers]}")
    return h.T


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("state_dict"); p.add_argument("out_dir"); p.add_argument("--kind", choices=["dqn", "ppo"], default="dqn")
    a = p.parse_args()
    export(a.state_dict, a.out_dir, a.kind)
